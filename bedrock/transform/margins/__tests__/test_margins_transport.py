@pytest.fixture(scope='module')
def fbs_2017() -> pd.DataFrame:
    return getFlowBySector(f'Margins_Transport_{ANCHOR}', download_FBAs_if_missing=True)


@pytest.mark.eeio_integration
def test_each_mode_reaches_its_own_control_total(fbs_2017: pd.DataFrame) -> None:
    """
    2017 is an identity: every mode reproduces its published give-up exactly.

    The coverage ratio is that give-up over the same year's freight revenue, so
    anything other than an exact match means the FBS lost or double-counted
    part of the allocator between the clean function and aggregation.
    """
    got = fbs_2017.groupby('SectorConsumedBy')['FlowAmount'].sum()
    for mode, commodity in tm.MODE_COMMODITIES.items():
        assert got[commodity] == pytest.approx(
            tm._mode_give_up_2017(commodity), rel=1e-9
        ), mode


@pytest.mark.eeio_integration
def test_the_column_is_the_published_transport_total(fbs_2017: pd.DataFrame) -> None:
    """
    The five modes together are the published column, to publication rounding.

    The give-up side totals 415,548 million against a receiving side of 414,559
    - 0.24% - which is rounding on the receiving side of the published Margins
    table, not a modelling gap. The FBS is built from the give-up side, so it
    lands above the receiving side by exactly that.
    """
    published = tm.published_transport_by_commodity().sum()
    built = fbs_2017['FlowAmount'].sum()
    assert built == pytest.approx(published, rel=0.0025)
    assert built > published


@pytest.mark.eeio_integration
def test_no_commodity_receives_margin_from_itself(fbs_2017: pd.DataFrame) -> None:
    """A transport commodity may not appear on the receiving side."""
    assert not set(fbs_2017['SectorProducedBy']) & MODE_CODES


@pytest.mark.eeio_integration
def test_the_fbs_reproduces_the_module_per_commodity(fbs_2017: pd.DataFrame) -> None:
    """
    The two paths to the same numbers agree, which is what makes both keepable.

    CAUTION: they agree to about 0.3%, not exactly, and the reason is worth
    knowing: the within-group weight is the published 2017 transport margin, and
    the FBS reads it off ``BEA_Detail_Supply``'s ``TRANS`` column - published in
    whole millions - while the module sums it out of the Margins transaction
    table, which is finer. Same quantity, different publication rounding. Any
    drift larger than that is a real divergence.
    """
    module = tm.mode_allocations(ANCHOR)
    for mode, commodity in tm.MODE_COMMODITIES.items():
        built = (
            fbs_2017[fbs_2017['SectorConsumedBy'] == commodity]
            .groupby('SectorProducedBy')['FlowAmount']
            .sum()
        )
        expected = module[mode]
        joined = pd.DataFrame({'fbs': built, 'module': expected}).fillna(0.0)
        drift = (joined['fbs'] - joined['module']).abs().sum() / expected.sum()
        assert drift < 0.005, f'{mode} drifts {drift:.2%} from the module'


@pytest.mark.eeio_integration
def test_a_nowcast_year_moves_off_the_anchor() -> None:
    """
    A non-anchor year builds, carries its own year, and is not 2017 again.

    The per-year files are one line over a shared method, so ``year`` reaching
    each source by inheritance is the whole mechanism - if it did not, every
    year would silently rebuild the anchor.
    """
    fbs = getFlowBySector('Margins_Transport_2022', download_FBAs_if_missing=True)
    assert set(fbs['Year'].astype(int)) == {2022}
    got = fbs.groupby('SectorConsumedBy')['FlowAmount'].sum()
    for mode, commodity in tm.MODE_COMMODITIES.items():
        assert got[commodity] == pytest.approx(
            tm.mode_control_total(mode, 2022), rel=1e-9
        )
        assert got[commodity] != pytest.approx(tm._mode_give_up_2017(commodity))
