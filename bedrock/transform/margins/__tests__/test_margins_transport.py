"""
Tests for the ``Margins_Transport_<year>`` FBS (#611, nowcast step 4c).

The fast tests here check the crosswalks and the clean functions. The
``eeio_integration`` ones generate the method and check that it reproduces
``nowcast_transport_margins`` - which is the property that justifies having two
paths to the same numbers at all.
"""

from __future__ import annotations

from pathlib import Path
from types import SimpleNamespace

import pandas as pd
import pytest

import bedrock.transform.iot.nowcast_transport_margins as tm
from bedrock.transform.flowbysector import getFlowBySector
from bedrock.transform.margins import transport
from bedrock.utils.config.settings import crosswalkpath

MAPPING_DIR = Path(tm.TRUCK_CROSSWALK_PATH).parent
ANCHOR = 2017

#: The five commodities that *give* transport margin up. None of them may be a
#: crosswalk target: BEA publishes zero transport margin received by all five.
MODE_CODES = set(tm.MODE_COMMODITIES.values())


def _sector_crosswalk(source: str) -> pd.DataFrame:
    return pd.read_csv(crosswalkpath / f'Sector_Crosswalk_{source}.csv', dtype=str)


# --------------------------------------------------------------------------
# the crosswalks the FBS reads
# --------------------------------------------------------------------------


@pytest.mark.parametrize('source', ['Census_SAS', 'STB_CRSR', 'BTS_FAF'])
def test_sector_crosswalk_targets_bea_detail_commodities(source: str) -> None:
    """
    Every target is a BEA 2017 code the published margins table knows.

    The method's target schema is BEA detail, so a NAICS code or a typo here
    would not fail - it would just never match, and the activity's margin would
    quietly vanish into the renormalisation.
    """
    crosswalk = _sector_crosswalk(source)
    published = tm.published_transport_by_commodity()
    unknown = set(crosswalk['Sector']) - set(published.index)
    assert not unknown, f'{source} targets non-commodity codes {sorted(unknown)}'
    assert set(crosswalk['SectorSourceName']) == {'BEA_2017_Code'}


@pytest.mark.parametrize('source', ['Census_SAS', 'STB_CRSR', 'BTS_FAF'])
def test_no_mode_delivers_margin_to_a_transport_commodity(source: str) -> None:
    """
    A mode may not hand margin to another mode.

    BEA publishes zero transport margin *received* by all five transport
    commodities, and ``transport_margin_column`` raises if a code turns up on
    both sides of the column. Catching it in the crosswalk says which file to
    fix instead of only that something is wrong.
    """
    assert not (set(_sector_crosswalk(source)['Sector']) & MODE_CODES)


@pytest.mark.parametrize('source', ['Census_SAS', 'STB_CRSR', 'BTS_FAF'])
def test_every_target_receives_published_transport_margin(source: str) -> None:
    """
    A target with no published ``TRANS`` cannot hold a share.

    The within-group weight *is* the published column, so an activity mapped
    only to zero-weight commodities has nowhere to put its margin and is
    silently dropped. The rail crosswalk writer already guards this; the guard
    belongs on all three.
    """
    crosswalk = _sector_crosswalk(source)
    published = tm.published_transport_by_commodity()
    weight = crosswalk['Sector'].map(published).fillna(0.0)
    stranded = sorted(
        set(
            crosswalk.loc[
                weight.groupby(crosswalk['Activity']).transform('sum') <= 0, 'Activity'
            ]
        )
    )
    assert not stranded, f'{source} activities with no weighted target: {stranded}'


def test_sector_crosswalks_are_a_faithful_re_emission() -> None:
    """
    The ``Sector_Crosswalk_*`` files still match the crosswalks they came from.

    They are generated by ``write_margins_sector_crosswalks.py`` and hold no
    judgement of their own, so an edit to a source crosswalk that was not
    followed by a re-run would leave the FBS and the module disagreeing about
    which commodity an activity serves - the exact failure the two-path design
    is meant to make visible.
    """
    rail_source = tm.load_rail_crosswalk()
    rail_source = rail_source[rail_source['bea_2017_commodity'] != '']
    rail_emitted = _sector_crosswalk('STB_CRSR')
    assert set(zip(rail_source['stcc5'], rail_source['bea_2017_commodity'])) == set(
        zip(rail_emitted['Activity'], rail_emitted['Sector'])
    )

    truck_source = tm.load_truck_crosswalk()
    truck_source = truck_source[truck_source['sas_group'] != tm.TRUCK_OTHER_GOODS]
    pipeline_source = tm.load_pipeline_crosswalk()
    sas_emitted = _sector_crosswalk('Census_SAS')
    assert set(
        zip(truck_source['sas_group'], truck_source['bea_2017_commodity'])
    ) | set(
        zip(pipeline_source['sas_naics'], pipeline_source['bea_2017_commodity'])
    ) == set(
        zip(sas_emitted['Activity'], sas_emitted['Sector'])
    )

    faf_source = tm.load_faf_sctg_crosswalk()
    faf_emitted = _sector_crosswalk('BTS_FAF')
    assert set(zip(faf_source['sctg'], faf_source['bea_2017_commodity'])) == set(
        zip(faf_emitted['Activity'], faf_emitted['Sector'])
    )


def test_every_allocator_key_is_in_the_crosswalk() -> None:
    """
    Every key the clean function emits can be mapped.

    An unmapped key is not an error in the machinery - it is dropped, and the
    remaining keys renormalise over its share. That is the quiet failure this
    catches.
    """
    keys = {
        'Census_SAS': set(
            tm.load_truck_group_revenue(ANCHOR)
            .drop(index=tm.TRUCK_OTHER_GOODS, errors='ignore')
            .index
        )
        | set(tm.load_pipeline_item_revenue(ANCHOR).index),
        'BTS_FAF': set(tm.load_faf_ton_miles('Water', ANCHOR).index),
    }
    for source, activity_keys in keys.items():
        mapped = set(_sector_crosswalk(source)['Activity'])
        assert not activity_keys - mapped, (
            f'{source} allocator keys missing from the crosswalk: '
            f'{sorted(activity_keys - mapped)}'
        )


