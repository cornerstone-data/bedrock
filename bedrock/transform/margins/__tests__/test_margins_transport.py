def test_flowable_names_every_mode() -> None:
    """The Flowable is the transport commodity's name, so all five need one."""
    assert set(transport.FLOWABLE) == set(tm.MODE_COMMODITIES)


def test_clean_parameter_must_name_a_mode() -> None:
    """
    A missing or misspelled ``clean_parameter`` has to raise, not default.

    It selects both the allocator and the control total, so a set that fell
    through to a default would allocate one mode's revenue against another
    mode's level and still balance.
    """
    for bad in (None, 'trucking', '484000'):
        with pytest.raises(ValueError, match='clean_parameter'):
            transport._mode(SimpleNamespace(config={'clean_parameter': bad}))


def test_a_mixed_year_activity_set_raises() -> None:
    """One control total cannot be applied to two years of shape."""
    fba = pd.DataFrame({'Year': ['2017', '2018'], 'FlowAmount': [1.0, 1.0]})
    with pytest.raises(ValueError, match='single year'):
        transport._year(fba)


def test_volume_allocator_applies_the_difficulty_multiplier() -> None:
    """
    Weighted ton-miles are not raw ton-miles.

    The 1/2/3 multiplier is the one part of the water and air method that is
    BEA's own construction rather than ours, so it has to actually reach the
    allocator.
    """
    raw = tm.load_faf_ton_miles('Water', ANCHOR)
    weighted = transport._volume_allocator('water', ANCHOR)
    assert set(weighted.index) == set(raw.index)
    assert (weighted >= raw).all()
    shares_raw = raw / raw.sum()
    shares_weighted = weighted / weighted.sum()
    assert not shares_raw.round(6).equals(shares_weighted.round(6))


def test_rail_allocator_drops_the_excluded_codes() -> None:
    """
    The service-class and empty-move codes never reach the FBS.

    They are 16.3% of released 2017 revenue, ``46111`` trailer-on-flatcar alone
    being 14.0%, and they name no commodity. Keeping them in the crosswalk file
    with a blank target is what makes the exclusion visible; this checks the FBS
    honours it rather than mapping them somewhere.
    """
    crosswalk = tm.load_rail_crosswalk()
    excluded = set(crosswalk.loc[crosswalk['bea_2017_commodity'] == '', 'stcc5'])
    assert excluded
    assert not set(transport._rail_allocator(ANCHOR).index) & excluded


def test_truck_allocator_drops_other_goods() -> None:
    """
    "Other goods" is 32.4% of 2017 motor carrier revenue and carries no

    commodity information. BEA drops it and lets the rest renormalise, and says
    so explicitly, so this is the method rather than an approximation of it.
    """
    allocator = tm.load_truck_group_revenue(ANCHOR).drop(
        index=tm.TRUCK_OTHER_GOODS, errors='ignore'
    )
    assert tm.TRUCK_OTHER_GOODS not in allocator.index
    assert len(allocator) == 10


